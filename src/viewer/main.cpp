enum class SliceExportFormat { Dxf = 0, Png = 1, Csv = 2 };

static int sliceAxisForBox(const AABB& box) {
    Vec3d size = box.size();
    if (size.x <= size.y && size.x <= size.z) return 0;
    if (size.y <= size.z) return 1;
    return 2;
}

static const char* sliceFormatName(SliceExportFormat format) {
    if (format == SliceExportFormat::Dxf) return "DXF";
    if (format == SliceExportFormat::Png) return "PNG";
    return "CSV";
}

static double sliceExtentU(const AABB& box, int axis) {
    Vec3d size = box.size();
    if (axis == 0) return size.y;
    return size.x;
}

static double sliceExtentV(const AABB& box, int axis) {
    Vec3d size = box.size();
    if (axis == 2) return size.y;
    return size.z;
}

static bool writeFileBytes(const std::string& path, const std::vector<unsigned char>& bytes) {
    FILE* file = fopen(path.c_str(), "wb");
    if (!file) return false;
    const bool ok = fwrite(bytes.data(), 1, bytes.size(), file) == bytes.size();
    fclose(file);
    return ok;
}

struct SliceExportJob {
    enum class State { Running, Succeeded, Failed, Canceled };

    std::string output;
    std::string name;
    SliceExportFormat format = SliceExportFormat::Dxf;
    uint64_t estimated = 0;

    std::atomic<State> state{State::Running};
    std::atomic<float> progress{0.0f};
    std::atomic<bool> cancelFlag{false};
    std::atomic<uint64_t> exported{0};
    std::atomic<uint32_t> attempts{0};
    bool notified = false;
    std::thread worker;

    void setMessage(const std::string& message) {
        std::lock_guard<std::mutex> lock(messageMutex);
        message_ = message;
    }

    std::string message() const {
        std::lock_guard<std::mutex> lock(messageMutex);
        return message_;
    }

    bool finished() const {
        State current = state.load();
        return current == State::Succeeded ||
               current == State::Failed ||
               current == State::Canceled;
    }

private:
    mutable std::mutex messageMutex;
    std::string message_;
};

