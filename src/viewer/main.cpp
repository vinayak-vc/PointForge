                                ImGui::SameLine();
                                if (ImGui::SmallButton("Go")) gotoAnnotation(annotations[i]);
                                ImGui::SameLine();
                                if (ImGui::SmallButton("x")) delIdx = i;
                                ImGui::TextDisabled("%.2f, %.2f, %.2f",
                                                    annotations[i].pos.x, annotations[i].pos.y, annotations[i].pos.z);
                                ImGui::PopID();
